"""A pull-request comment: short enough that people actually read it.

The full report belongs in an artifact. What belongs in a PR is the answer to
one question — did this change make the architecture better or worse?
"""

from __future__ import annotations

BADGE = {"A": "🟢", "B": "🟢", "C": "🟡", "D": "🟠", "F": "🔴"}
SEVERITY_LABEL = {"critical": "critical", "major": "major", "minor": "minor"}


def render(report: dict, limit: int = 5) -> str:
    health = report["health"]
    summary = report["summary"]
    diff = report.get("comparison")
    lines: list[str] = []

    headline = f"### {BADGE.get(health['grade'], '⚪')} ArchRay — {health['score']}/100 ({health['grade']})"
    if diff:
        arrow = "▲" if diff["score_delta"] > 0 else "▼" if diff["score_delta"] < 0 else "="
        headline += f" &nbsp; {arrow} {diff['score_delta']:+} pts"
    lines.append(headline)
    lines.append("")
    lines.append(f"`{summary['modules']} modules` · `{summary['sloc']} lines` · "
                 f"`{summary['findings']} findings` · `{summary['patterns']} patterns` · "
                 f"`{summary['cycles']} cycles`")

    if diff:
        lines += ["", f"**{diff['verdict']}**"]
        if diff["new"]:
            lines += ["", f"<details open><summary>{diff['new_count']} new findings</summary>",
                      "", "| Severity | Finding | Location |", "|---|---|---|"]
            for item in diff["new"][:limit]:
                lines.append(f"| {SEVERITY_LABEL.get(item['severity'], item['severity'])} "
                             f"| {item['title']} | `{item['file']}:{item['line']}` |")
            if diff["new_count"] > limit:
                lines.append(f"| … | {diff['new_count'] - limit} more | |")
            lines += ["", "</details>"]
        if diff["fixed"]:
            fixed = ", ".join(f"`{item['symbol'] or item['file']}`"
                              for item in diff["fixed"][:4])
            lines += ["", f"✅ Resolved {diff['fixed_count']}: {fixed}"]
    else:
        lines += ["", "<details open><summary>Most urgent technical debt</summary>", "",
                  "| Severity | Finding | Location |", "|---|---|---|"]
        for item in report["top_debt"][:limit]:
            lines.append(f"| {SEVERITY_LABEL.get(item['severity'], item['severity'])} "
                         f"| {item['title']} | `{item['file']}:{item['line']}` |")
        lines += ["", "</details>"]

    evolution = report.get("history") or {}
    if evolution.get("hotspots"):
        spot = evolution["hotspots"][0]
        lines += ["", f"🔥 Riskiest file: `{spot['file']}` — {spot['revisions']} changes, "
                  f"complexity {spot['complexity']}"]

    diagram = (report.get("diagrams") or {}).get("packages")
    if diagram:
        lines += ["", "<details><summary>Architecture view</summary>", "", "```mermaid",
                  diagram, "```", "", "</details>"]

    lines += ["", "<sub>Generated by ArchRay · full report in the workflow artifact</sub>"]
    return "\n".join(lines)
